import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const {previewDefaults,previewKind,previewStep} = await import('data:text/javascript;base64,' + readFileSync(new URL('../extension/preview-navigation.js', import.meta.url)).toString('base64'));
const file = name => ({name,path:name,kind:'file'});
const entries = ['01.jpg','02.txt','03.mp3','04.pdf','05.mp4','06.exe'].map(file);
entries.splice(2,0,{...file('fake.png'),kind:'directory'});
assert.equal(previewStep(entries,'01.jpg',1,previewDefaults).name,'03.mp3');
assert.equal(previewStep(entries,'05.mp4',1,previewDefaults).name,'01.jpg');
assert.equal(previewStep(entries,'01.jpg',-1,previewDefaults).name,'05.mp4');
assert.equal(previewStep(entries,'02.txt',1,previewDefaults).name,'03.mp3');
assert.equal(previewStep(entries,'02.txt',-1,previewDefaults).name,'01.jpg');
assert.equal(previewStep(entries,'01.jpg',1,{...previewDefaults,text:true}).name,'02.txt');
assert.equal(previewStep(entries,'03.mp3',1,{...previewDefaults,pdf:true}).name,'04.pdf');
assert.equal(previewStep(entries,'01.jpg',1,{}),null);
assert.equal(previewStep([],null,1,previewDefaults),null);
assert.equal(previewStep([file('a.jpg')],'a.jpg',-1,previewDefaults).name,'a.jpg');
assert.equal(previewKind('UPPER.JPG'),'image');
assert.equal(previewKind('unknown.exe'),null);
assert.deepEqual(entries.map(x=>x.name),['01.jpg','02.txt','fake.png','03.mp3','04.pdf','05.mp4','06.exe']);
console.log('PASS preview order, both wrap directions, skipped files/directories, optional text/PDF, empty/singleton and case handling');
